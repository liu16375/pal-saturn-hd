"""Generate sdlpal/sattextcolor.h: Saturn text colour code -> port palette index.

On the Saturn, text is drawn into the UI bitmap (VDP2 NBG1), which uses its own colour bank
(ALLDAT.NEW palette 3, offset 0x600; verified in an emulator: CRAM bank 3, name pixel 214 = (248,248,112)).
The glyph renderer 0x06052d0c first translates the DOS-style colour code it is given (switch at 0x06052d7c):
    0->1, 15->68, 23/24->81, 26->0xA8, 28/30->0x96, 43..45->0xD6, 47->0xCE, 60->0xD6, 78->10, 79->0xCE,
    94->95, 0x8D->0xB4, 0xBD->68, 0xEE->10, 0xFA/0xFB/0xFC->0xD6, 0xFD->11, anything else unchanged.
The port has a single (scene) palette, so each code is mapped to the scene-palette entry (pat.mkf #0)
nearest to UIpal[translated code].
usage: python tools/gen_textcolor.py disc game sdlpal/sattextcolor.h"""
import struct, sys

SATMAP = {0: 1, 15: 68, 23: 81, 24: 81, 26: 0xA8, 28: 0x96, 30: 0x96, 43: 0xD6, 44: 0xD6, 45: 0xD6,
          47: 0xCE, 60: 0xD6, 78: 10, 79: 0xCE, 94: 95, 0x8D: 0xB4, 0xBD: 68, 0xEE: 10,
          0xFA: 0xD6, 0xFB: 0xD6, 0xFC: 0xD6, 0xFD: 11}


def main():
    disc, game, out = sys.argv[1:4]
    A = open(disc + '/ALLDAT.NEW', 'rb').read()
    ui = [((x & 31) << 3, ((x >> 5) & 31) << 3, ((x >> 10) & 31) << 3) for x in struct.unpack_from('>256H', A, 0x600)]
    d = open(game + '/pat.mkf', 'rb').read()
    o = struct.unpack_from('<2I', d)
    p = d[o[0]:o[1]]
    scene = [(p[i * 3] * 4, p[i * 3 + 1] * 4, p[i * 3 + 2] * 4) for i in range(256)]
    tab = []
    for c in range(256):
        t = ui[SATMAP.get(c, c)]
        best = min(range(1, 256), key=lambda i: (sum((a - b) ** 2 for a, b in zip(scene[i], t)), i != c))
        if t == (0, 0, 0): best = 0
        tab.append(best)
    with open(out, 'w') as f:
        f.write('/* generated by tools/gen_textcolor.py - Saturn text colour code -> scene palette index */\n')
        f.write('static const unsigned char g_rgSatTextColor[256] = {\n')
        for i in range(0, 256, 16):
            f.write('   ' + ', '.join('0x%02X' % x for x in tab[i:i + 16]) + ',\n')
        f.write('};\n')
        f.write('/* raw UI-palette (ALLDAT palette 3, port bank 3) index after the Saturn translation switch */\n')
        f.write('static const unsigned char g_rgSatTextUI[256] = {\n')
        raw = [SATMAP.get(c, c) for c in range(256)]
        for i in range(0, 256, 16):
            f.write('   ' + ', '.join('0x%02X' % x for x in raw[i:i + 16]) + ',\n')
        f.write('};\n')
    print('wrote', out)


if __name__ == '__main__':
    main()
